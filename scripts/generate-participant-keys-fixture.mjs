// Writes fixtures/sharing-v1/participant-keys.json: a web-written shared backup
// that turns on participant keys, adds a viewer's recovery key (carried by the
// owner), replaces the viewer's lost key with a recovery-authorized rotation,
// and removes the recovery key. Kotlin verifies and decrypts every revision.
// Regenerate only when the format changes: `npm run fixtures:participant-keys`.
import { writeFile } from "node:fs/promises";
import { webcrypto as crypto } from "node:crypto";
import {
  createAuthorizedKeyRotationV1,
  createParticipantKeyAdditionV1,
  createParticipantKeyRemovalV1,
  createSharingRecoveryKeyV1,
  generateSharingRecoveryCode,
} from "../dist/sharing/participant-keys.js";
import { sharedBackupParticipants } from "../dist/sharing/index.js";
import { createSharedBackupEnvelopeV1 } from "../dist/sharing/web-crypto.js";

const appId = "fixture-app";
const backupId = "participant-keys";
const codec = { serialize: (value) => value, parse: (value) => value };

async function exportableIdentity() {
  const encryption = await crypto.subtle.generateKey({ name: "ECDH", namedCurve: "P-256" }, true, ["deriveBits"]);
  const signing = await crypto.subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, ["sign", "verify"]);
  const raw = async (key) => Buffer.from(await crypto.subtle.exportKey("raw", key)).toString("base64url");
  const { createSharingPublicKeyV1 } = await import("../dist/sharing/web-crypto.js");
  const publicKey = await createSharingPublicKeyV1(await raw(encryption.publicKey), await raw(signing.publicKey), crypto);
  return {
    identity: { publicKey, encryptionPrivateKey: encryption.privateKey, signingPrivateKey: signing.privateKey },
    fixture: {
      publicKey,
      privateKeys: {
        encryption: await crypto.subtle.exportKey("jwk", encryption.privateKey),
        signing: await crypto.subtle.exportKey("jwk", signing.privateKey),
      },
    },
  };
}

function inputs(envelope) {
  return sharedBackupParticipants(envelope).map(({ role, accepted, ...publicKey }) => ({
    publicKey,
    role,
    ...(accepted ? { accepted } : {}),
  }));
}

async function write(author, previous, payload, extra = {}) {
  return await createSharedBackupEnvelopeV1(
    payload,
    codec,
    author,
    {
      appId,
      backupId,
      participants: extra.participants ?? inputs(previous),
      ...(previous ? { previous } : {}),
      ...(extra.participantKeys ? { participantKeys: extra.participantKeys } : {}),
    },
    { crypto },
  );
}

const owner = await exportableIdentity();
const viewer = await exportableIdentity();
const replacement = await exportableIdentity();
const recoveryCode = await generateSharingRecoveryCode({ crypto });
const recovery = await createSharingRecoveryKeyV1({ appId, code: recoveryCode }, { crypto });

const genesis = await write(owner.identity, undefined, { items: ["genesis"] }, {
  participants: [
    { publicKey: owner.identity.publicKey, role: "owner" },
    { publicKey: viewer.identity.publicKey, role: "viewer" },
  ],
});
const enabled = await write(owner.identity, genesis, { items: ["enabled"] }, {
  participantKeys: { policy: true },
});
const addition = await createParticipantKeyAdditionV1(
  {
    appId,
    principalKeyId: viewer.identity.publicKey.keyId,
    authorizer: viewer.identity,
    key: recovery.identity,
    purpose: "recovery",
    sealedPrivateKeys: recovery.sealedPrivateKeys,
  },
  { crypto },
);
const withRecovery = await write(owner.identity, enabled, { items: ["with-recovery"] }, {
  participantKeys: { add: [addition] },
});
const rotation = await createAuthorizedKeyRotationV1(
  {
    appId,
    fromKeyId: viewer.identity.publicKey.keyId,
    authorizer: recovery.identity,
    replacement: replacement.identity,
  },
  { crypto },
);
const rotated = await write(owner.identity, withRecovery, { items: ["rotated"] }, {
  participantKeys: { rotation },
});
const removal = await createParticipantKeyRemovalV1(
  { appId, authorizer: replacement.identity, key: addition },
  { crypto },
);
const removed = await write(owner.identity, rotated, { items: ["removed"] }, {
  participantKeys: { remove: [removal] },
});

await writeFile(
  new URL("../fixtures/sharing-v1/participant-keys.json", import.meta.url),
  JSON.stringify(
    {
      provenance:
        "Generated by scripts/generate-participant-keys-fixture.mjs from the web package. " +
        "Regenerate only when the participant-keys format changes.",
      appId,
      backupId,
      recoveryCode,
      recoveryKeyId: recovery.identity.publicKey.keyId,
      owner: owner.fixture,
      viewer: viewer.fixture,
      replacement: replacement.fixture,
      envelopes: { genesis, enabled, withRecovery, rotated, removed },
      expected: {
        payloads: {
          genesis: { items: ["genesis"] },
          enabled: { items: ["enabled"] },
          withRecovery: { items: ["with-recovery"] },
          rotated: { items: ["rotated"] },
          removed: { items: ["removed"] },
        },
      },
    },
    null,
    2,
  ) + "\n",
);
console.log("Wrote fixtures/sharing-v1/participant-keys.json");
