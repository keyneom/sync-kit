// Writes fixtures/v2/snapshot-recovery.json: web-written v2 private snapshots —
// plain, with a recovery code, re-locked under a new passkey after recovery,
// and migrated back to v1. Kotlin decrypts every one, with the passkey secret
// and with the recovery code. Regenerate only when the v2 format changes:
// `npm run fixtures:snapshot-recovery`.
import { writeFile } from "node:fs/promises";
import {
  createV1EnvelopeCrypto,
  createWebCryptoBackend,
  defineV1CompatibilityProfile,
  deriveContentKey,
  generateRecoveryCode,
} from "../dist/crypto/index.js";

const backend = createWebCryptoBackend();
const profileInput = {
  appId: "fixture-recovery",
  filename: "fixture-recovery.json",
  aad: "fixture-recovery-v1",
  hkdfInfo: "fixture-recovery content key",
  compression: "gzip-if-smaller",
  passkey: {
    rpName: "Fixture Recovery",
    userName: "fixture",
    userDisplayName: "Fixture",
    algorithm: -7,
    residentKey: "required",
    userVerification: "required",
    timeoutMs: 60000,
  },
};
const profile = defineV1CompatibilityProfile({ ...profileInput, readVersions: [1, 2], writeVersion: 2 });
const codec = {
  serialize: (value) => value,
  parse: (value) => value,
  merge: (local) => local,
  fingerprint: (value) => JSON.stringify(value),
  updatedAt: (value) => value.updatedAt,
};
const crypto = createV1EnvelopeCrypto(profile, codec, backend);
const b64 = (bytes) => Buffer.from(bytes).toString("base64url");

async function passkey(credentialId) {
  const secret = backend.randomBytes(32);
  const metadata = {
    credentialId,
    rpId: "fixture.example",
    prfInput: backend.randomBytes(32),
    kdfSalt: backend.randomBytes(32),
  };
  return {
    key: await deriveContentKey(profile, secret, metadata.kdfSalt, backend),
    metadata,
    fixture: { credentialId, prfSecret: b64(secret), kdfSalt: b64(metadata.kdfSalt) },
  };
}

const value = (label) => ({ items: [label, "shared"], updatedAt: `2026-09-23T12:00:0${label.length % 10}.000Z` });
const original = await passkey("credential-original");
const replacement = await passkey("credential-replacement");
const recoveryCode = await generateRecoveryCode(backend);

const plain = await crypto.encrypt(value("plain"), original.key, original.metadata);
const withRecovery = await crypto.setRecoveryCode(plain, original.key, recoveryCode);
const relocked = await crypto.relockWithRecoveryCode(withRecovery, recoveryCode, replacement, value("relocked"));
const migrated = await crypto.migrate(withRecovery, original.key, 1);

await writeFile(
  new URL("../fixtures/v2/snapshot-recovery.json", import.meta.url),
  JSON.stringify(
    {
      provenance:
        "Generated by scripts/generate-snapshot-recovery-fixture.mjs from the web package. " +
        "Regenerate only when the snapshot v2 format changes.",
      profile: profileInput,
      recoveryCode,
      passkeys: { original: original.fixture, replacement: replacement.fixture },
      envelopes: { plain, withRecovery, relocked, migrated },
      expected: {
        plain: value("plain"),
        withRecovery: value("plain"),
        relocked: value("relocked"),
        migrated: value("plain"),
      },
    },
    null,
    2,
  ) + "\n",
);
console.log("Wrote fixtures/v2/snapshot-recovery.json");
